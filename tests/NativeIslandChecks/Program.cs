static void CompareArchives(string first,string second,string name)
{
using(var original=ZipFile.OpenRead(first))
using(var reread=ZipFile.OpenRead(second))
{
 int compared=0;
 foreach(var entry in original.Entries.Where(e=>e.Name.EndsWith(".xml") && (e.FullName.Contains("/meshes/")||e.FullName.Contains("/normalmaps/")||e.Name is "rd3d.xml" or "gamedata.xml" || e.Name==name+".xml")))
 {
  var next=reread.GetEntry(entry.FullName);if(next is null)throw new Exception("Roundtrip missing: "+entry.FullName);
  using var a=entry.Open();using var b=next.Open();
  var ax=System.Xml.Linq.XDocument.Load(a);var bx=System.Xml.Linq.XDocument.Load(b);
  // Internal zlib lengths are regenerated by FileDBReader, not gameplay data.
  foreach(var doc in new[]{ax,bx}) foreach(var length in doc.Descendants("AreaManagerData").Descendants("ByteCount").ToArray())length.Remove();
  XElement Canonical(XElement element)
  {
   var children=element.Elements().ToArray();
   if(children.Length>0)return new XElement(element.Name,element.Attributes(),children.Select(Canonical));
   var text=element.Value.Trim();var tokens=text.Split((char[]?)null,StringSplitOptions.RemoveEmptyEntries);
   if(tokens.Length>0&&tokens.All(t=>decimal.TryParse(t.Replace(',','.'),System.Globalization.NumberStyles.Float,System.Globalization.CultureInfo.InvariantCulture,out _)))
    text=string.Join(" ",tokens.Select(t=>decimal.Parse(t.Replace(',','.'),System.Globalization.NumberStyles.Float,System.Globalization.CultureInfo.InvariantCulture).ToString("G29",System.Globalization.CultureInfo.InvariantCulture)));
   return new XElement(element.Name,element.Attributes(),text);
  }
  if(!XNode.DeepEquals(Canonical(ax.Root!),Canonical(bx.Root!)))throw new Exception("Roundtrip changed data: "+entry.FullName);
  compared++;
 }
 Console.WriteLine("PASS: semantic XML roundtrip, "+compared+" files.");
}

