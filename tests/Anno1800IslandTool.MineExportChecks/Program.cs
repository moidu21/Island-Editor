using System.IO.Compression;
using System.Xml.Linq;
using Anno1800IslandTool.Pipeline.Import;
using Anno1800IslandTool.Pipeline.Export;
using Anno1800IslandTool.Pipeline.Services;
if(args.Length!=2||File.Exists(args[1]))throw new ArgumentException("Original ZIP and new test output ZIP required.");
var project=new IslandImporter().Import(args[0],new ImportOptions{ReadPagePayloads=false});
var count=project.Root.SlotObjects.Count;
var original=project.Root.SlotObjects.Select(s=>s.ObjectId).ToHashSet();
var a=MineSlotService.TerrainPoint(project,234.5,201.5);
var b=MineSlotService.TerrainPoint(project,243.7,200.28);
var ids=MineSlotService.Add(project,new[]{new MineSlotPlacement(MineSlotService.Catalog.Single(m=>m.Guid=="1010501"),a,b)});
Console.WriteLine($"Added iron mine {ids[0]}, root slots {count} -> {project.Root.SlotObjects.Count}");
Console.WriteLine(new IslandExporter().Export(project,args[1],new ExportOptions()).Summary);
var reloaded=new IslandImporter().Import(args[1],new ImportOptions{ReadPagePayloads=false});
if(reloaded.Root.SlotObjects.Count!=count+2||original.Except(reloaded.Root.SlotObjects.Select(s=>s.ObjectId)).Any())throw new Exception("Lost slots");
var mine=reloaded.Root.SlotObjects.Single(s=>s.ObjectId==ids[0]);if(mine.ObjectGuid!="1010501")throw new Exception("Wrong resource");
var doc=XDocument.Parse(reloaded.RawContent.GameDataText);
var obj=doc.Descendants("GameObject").Elements("objects").Elements().Single(e=>e.Element("ID")?.Value==ids[0].ToString());
if(obj.Element("guid")?.Value!="1010501")throw new Exception("GameData mine missing");
var work=reloaded.Root.SlotObjects.Single(s=>!original.Contains(s.ObjectId)&&s.ObjectId!=ids[0]);
if(work.ObjectGuid!="1000253")throw new Exception("Work area missing");
if(!doc.Descendants("ID").Any(e=>e.Value==work.ObjectId.ToString()&&e.Parent!.Element("BezierPath")!=null))throw new Exception("Path missing");
using var input=ZipFile.OpenRead(args[0]);using var output=ZipFile.OpenRead(args[1]);
var a7=input.Entries.Single(e=>e.FullName.EndsWith(".a7me"));using var r1=new StreamReader(a7.Open());using var r2=new StreamReader(output.GetEntry(a7.FullName)!.Open());
if(!XNode.DeepEquals(XDocument.Parse(r1.ReadToEnd()),XDocument.Parse(r2.ReadToEnd())))throw new Exception("Unnecessary a7me change");
Console.WriteLine("PASS: mine and work area survive export/reimport, original slots retained, a7me unchanged.");
